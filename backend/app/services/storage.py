"""S3-compatible object storage (ARCHITECTURE.md §10 media, §15 invoice PDFs).

Works with AWS S3, Cloudflare R2, DigitalOcean Spaces and SeaweedFS/MinIO locally.
Files are private: the API streams them to authorized users; keys never contain
user-supplied names. boto3 is blocking, so calls run in a worker thread.
"""

import asyncio
import hashlib
import uuid
from dataclasses import dataclass
from functools import lru_cache
from typing import TYPE_CHECKING, Any

import boto3
from botocore.config import Config
from botocore.exceptions import ClientError
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import get_settings
from app.core.exceptions import AppError
from app.core.logging import get_logger
from app.models import StoredObject

if TYPE_CHECKING:
    from mypy_boto3_s3 import S3Client

log = get_logger(__name__)


class StorageUnavailable(AppError):
    status, code, title = 503, "storage_unavailable", "File storage is not available right now"


@lru_cache
def _client() -> "S3Client":
    settings = get_settings()
    return boto3.client(
        "s3",
        endpoint_url=settings.s3_endpoint or None,
        region_name=settings.s3_region,
        aws_access_key_id=settings.s3_access_key or None,
        aws_secret_access_key=settings.s3_secret_key or None,
        config=Config(signature_version="s3v4", s3={"addressing_style": "path"}, retries={"max_attempts": 3}),
    )


_bucket_ready = False


def _ensure_bucket() -> None:
    global _bucket_ready
    if _bucket_ready:
        return
    bucket = get_settings().s3_bucket
    try:
        _client().head_bucket(Bucket=bucket)
    except ClientError:
        if get_settings().is_production:
            raise  # production buckets are provisioned, never created by the app
        _client().create_bucket(Bucket=bucket)
        log.info("storage_bucket_created", bucket=bucket)
    _bucket_ready = True


def _put(key: str, data: bytes, content_type: str) -> None:
    _ensure_bucket()
    _client().put_object(Bucket=get_settings().s3_bucket, Key=key, Body=data, ContentType=content_type)


def _get(key: str) -> bytes:
    response: dict[str, Any] = _client().get_object(Bucket=get_settings().s3_bucket, Key=key)  # type: ignore[assignment]
    body: bytes = response["Body"].read()
    return body


@dataclass(frozen=True)
class Stored:
    object_id: uuid.UUID
    key: str


async def put(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID | None,
    data: bytes,
    content_type: str,
    purpose: str,
    key_prefix: str,
    extension: str,
) -> Stored:
    """Store bytes under a random key and record them in ``stored_objects`` (same transaction)."""
    object_id = uuid.uuid4()
    owner = f"tenants/{tenant_id}" if tenant_id else "platform"
    key = f"{owner}/{key_prefix}/{object_id}.{extension}"
    try:
        await asyncio.to_thread(_put, key, data, content_type)
    except Exception as exc:
        log.warning("storage_put_failed", purpose=purpose, exc_info=True)
        raise StorageUnavailable() from exc
    session.add(
        StoredObject(
            id=object_id,
            tenant_id=tenant_id,
            bucket=get_settings().s3_bucket,
            object_key=key,
            mime_type=content_type,
            size_bytes=len(data),
            checksum_sha256=hashlib.sha256(data).hexdigest(),
            purpose=purpose,
            scan_status="skipped" if purpose == "invoice_pdf" else "pending",  # generated by us
        )
    )
    await session.flush()
    return Stored(object_id, key)


async def get(stored: StoredObject) -> bytes:
    try:
        return await asyncio.to_thread(_get, stored.object_key)
    except Exception as exc:
        log.warning("storage_get_failed", purpose=stored.purpose, exc_info=True)
        raise StorageUnavailable() from exc
